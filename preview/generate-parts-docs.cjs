#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const partsDir = path.join(root, 'src', 'main', 'resources', 'parts');
const output = path.join(root, 'docs', 'parts.md');

function readParts() {
  const index = JSON.parse(fs.readFileSync(path.join(partsDir, 'index.json'), 'utf8'));
  if (index.schema_version !== 1 || !Array.isArray(index.parts)) throw new Error('Invalid parts index');
  return index.parts.map(file => JSON.parse(fs.readFileSync(path.join(partsDir, file), 'utf8')))
    .sort((a, b) => a.id.localeCompare(b.id));
}

function parameter(definition) {
  if (definition.type === 'integer') return `integer, ${definition.min}..${definition.max}; default ${definition.default}`;
  if (definition.type === 'enum') return `enum (${definition.values.join(', ')}); default ${definition.default}`;
  if (definition.type === 'material') return `palette role; default \`${definition.default}\``;
  throw new Error(`Unsupported parameter type: ${definition.type}`);
}

function render(parts = readParts()) {
  const lines = [
    '# Architectural parts',
    '',
    'Generated by `preview/generate-parts-docs.cjs`; do not edit this file by hand.',
    '',
    'Parts are bounded plan fragments. Their material defaults are semantic caller palette roles, so a plan must map each selected role to a block state. Cells emitted by a part remain owned by the component that calls it. Stair roles named `stair-up-south` must resolve to a bottom, south-facing stair. Their public `facing` parameter means the ascending direction; local straight flights rise toward +Z and part rotation supplies the other directions.',
    ''
  ];
  for (const part of parts) {
    lines.push(`## \`${part.id}\``, '', part.description, '');
    lines.push(`- Style: \`${part.style}\``);
    lines.push(`- Provenance: ${part.provenance.author} — ${part.provenance.project}`);
    lines.push(`- Local bounds: \`${JSON.stringify(part.bounds.min)}\` to \`${JSON.stringify(part.bounds.max)}\` (max exclusive).`);
    lines.push(`- Test call: \`${JSON.stringify(part.test)}\``);
    if (part.rotation) lines.push(`- Rotation: \`${part.rotation.param}\` (${Object.entries(part.rotation.turns).map(([name, turns]) => `${name}=${turns}`).join(', ')}).`);
    lines.push('', '| Parameter | Contract |', '| --- | --- |');
    for (const [name, definition] of Object.entries(part.parameters)) lines.push(`| \`${name}\` | ${parameter(definition)} |`);
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

if (require.main === module) {
  fs.writeFileSync(output, render());
  process.stdout.write(`${path.relative(root, output)}\n`);
}

module.exports = {readParts, render};
